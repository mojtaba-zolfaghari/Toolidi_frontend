/**
 * ساختار پاسخ استاندارد API برای عملیات‌های موفق و ناموفق.
 * در بک‌اند ویژگی‌های null هنگام سریالایز حذف می‌شوند،
 * بنابراین فیلدها به صورت اختیاری تعریف شده‌اند.
 */
export interface Result<T> {
  /** آیا عملیات موفق بوده است؟ */
  isSuccess: boolean;
  /** داده‌ی بازگشتی در صورت موفقیت */
  data?: T;
  /** پیام خطا در صورت شکست */
  errorMessage?: string;
}

/**
 * ساختار لیست صفحه‌بندی‌شده‌ی بازگشتی از API.
 */
export interface PagedList<T> {
  /** آیتم‌های صفحه‌ی جاری */
  items: T[];
  /** تعداد کل آیتم‌ها در تمام صفحات */
  totalCount: number;
  /** شماره‌ی صفحه‌ی جاری (یک‌مبنا) */
  pageNumber: number;
  /** تعداد آیتم در هر صفحه */
  pageSize: number;
  /** آیا صفحه‌ی بعدی وجود دارد؟ */
  hasNextPage: boolean;
}
